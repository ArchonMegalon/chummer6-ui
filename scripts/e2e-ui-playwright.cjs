async function executeAddWorkflow(page, workflow) {
  console.log(`checking add workflow: ${workflow.quickActionId}`);
  await selectWorkspaceSurface(page, workflow.tabId, workflow.actionId);
  await page.waitForSelector(`[data-section-quick-action="${workflow.quickActionId}"]`, { timeout: 15000 });
  const beforeCount = await countBodyOccurrences(page, workflow.resultMarker);
  await page.locator(`[data-section-quick-action="${workflow.quickActionId}"]`).click();
  await expectPremiumDialogPosture(page, workflow.dialogTitle);

  const dialogText = await page.locator('.desktop-dialog').innerText();
  for (const marker of workflow.dialogMarkers) {
    expectTextIncludes(dialogText, marker, `${workflow.dialogTitle} dialog`);
  }

  await page.locator('#dialogBackdrop').getByRole('button', { name: workflow.confirmButton }).click();
  await page.waitForFunction(() => !document.querySelector('#dialogBackdrop'), { timeout: 15000 });
  try {
    await page.waitForFunction(
      ({ marker, beforeCount }) => {
        const text = document.body.innerText || '';
        const escaped = marker.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        return (text.match(new RegExp(escaped, 'g')) || []).length > beforeCount;
      },
      { marker: workflow.resultMarker, beforeCount },
      { timeout: 15000 });
  } catch (error) {
    const bodyText = await page.locator('body').innerText();
    throw new Error(
      `Expected ${workflow.quickActionId} to add another visible '${workflow.resultMarker}' row. Body excerpt: ${bodyText.slice(0, 2400)}`,
      { cause: error });
  }

  await expectPremiumSurfaceQuality(page, `${workflow.quickActionId} workspace`);
}

async function countBodyOccurrences(page, marker) {
  return await page.evaluate((value) => {
    const text = document.body.innerText || '';
    const escaped = value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    return (text.match(new RegExp(escaped, 'g')) || []).length;
  }, marker);
}

