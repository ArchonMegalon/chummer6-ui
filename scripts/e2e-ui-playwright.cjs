async function expectVisibleSelector(page, selector, context) {
  await page.waitForSelector(selector, { timeout: 15000, state: 'attached' });
  const count = await page.locator(selector).count();
  if (count < 1) {
    throw new Error(`Expected ${context} selector '${selector}' to be present.`);
  }
}

async function expectSelectorCountAtLeast(page, selector, expectedCount, context) {
  await page.waitForSelector(selector, { timeout: 15000, state: 'attached' });
  const count = await page.locator(selector).count();
  if (count < expectedCount) {
    throw new Error(`Expected at least ${expectedCount} ${context} nodes for '${selector}', got ${count}.`);
  }
}

async function fillDialogTextField(dialog, label, value) {
  const field = dialog.locator(`input[aria-label="${label}"], textarea[aria-label="${label}"]`).first();
  await field.fill(value);
  await field.evaluate(element => element.dispatchEvent(new Event('input', { bubbles: true })));
}

async function waitForDialogTitle(page, expectedText) {
  await page.waitForFunction((expected) => {
    const title = document.querySelector('#dialogTitle');
    return title && title.textContent && title.textContent.toLowerCase().includes(expected);
  }, expectedText.toLowerCase(), { timeout: 15000 });
}

async function expectPremiumDialogPosture(page, expectedTitle) {
  await waitForDialogTitle(page, expectedTitle);

  const dialog = page.locator('.desktop-dialog').first();
  await dialog.waitFor({ state: 'visible', timeout: 15000 });

  const box = await dialog.boundingBox();
  const viewport = page.viewportSize() || { width: 1280, height: 720 };
  if (!box) {
    throw new Error(`Expected '${expectedTitle}' dialog to have a measurable box.`);
  }

  const horizontalSlack = Math.max(12, viewport.width * 0.015);
  const verticalSlack = Math.max(12, viewport.height * 0.015);
  if (box.x < 0 || box.y < 0 || box.x + box.width > viewport.width + 1 || box.y + box.height > viewport.height + 1) {
    throw new Error(`Expected '${expectedTitle}' dialog to fit inside ${viewport.width}x${viewport.height}, got ${JSON.stringify(box)}.`);
  }

  if (box.x < horizontalSlack || box.y < verticalSlack) {
    throw new Error(`Expected '${expectedTitle}' dialog to keep premium viewport breathing room, got ${JSON.stringify(box)}.`);
  }

  const dialogText = await dialog.innerText();
  expectNoGeneratedAiCopy(dialogText, `${expectedTitle} dialog`);
  await expectPremiumSurfaceQuality(page, `${expectedTitle} dialog`, '.desktop-dialog');

  const contrastFailures = await dialog.evaluate((root) => {
    function parseColor(value) {
      const match = /^rgba?\((\d+),\s*(\d+),\s*(\d+)(?:,\s*([0-9.]+))?\)$/.exec(value || '');
      if (!match) {
        return null;
      }

      return {
        r: Number(match[1]) / 255,
        g: Number(match[2]) / 255,
        b: Number(match[3]) / 255,
        a: match[4] === undefined ? 1 : Number(match[4])
      };
    }

    function linear(channel) {
      return channel <= 0.03928 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
    }

    function luminance(color) {
      return 0.2126 * linear(color.r) + 0.7152 * linear(color.g) + 0.0722 * linear(color.b);
    }

    function contrastRatio(foreground, background) {
      const l1 = luminance(foreground);
      const l2 = luminance(background);
      return (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
    }

    function effectiveBackground(element) {
      let current = element;
      while (current instanceof Element) {
        const color = parseColor(getComputedStyle(current).backgroundColor);
        if (color && color.a > 0.01) {
          return color;
        }

        current = current.parentElement;
      }

      return { r: 1, g: 1, b: 1, a: 1 };
    }

    return Array.from(root.querySelectorAll('span, p, label, button, input, textarea, .dialog-input, .dialog-note, .dialog-grid-key, .dialog-grid-value'))
      .filter((node) => {
        const style = getComputedStyle(node);
        const rect = node.getBoundingClientRect();
        const text = node instanceof HTMLInputElement || node instanceof HTMLTextAreaElement
          ? node.value || node.placeholder || node.getAttribute('aria-label') || ''
          : node.textContent || '';
        return text.trim().length > 0
          && style.visibility !== 'hidden'
          && style.display !== 'none'
          && rect.width > 0
          && rect.height > 0
          && !node.hasAttribute('disabled');
      })
      .map((node) => {
        const style = getComputedStyle(node);
        const foreground = parseColor(style.color);
        const background = effectiveBackground(node);
        const ratio = foreground && background ? contrastRatio(foreground, background) : 99;
        const text = node instanceof HTMLInputElement || node instanceof HTMLTextAreaElement
          ? node.value || node.placeholder || node.getAttribute('aria-label') || ''
          : node.textContent || '';
        return {
          text: text.trim().slice(0, 80),
          ratio: Math.round(ratio * 100) / 100
        };
      })
      .filter((item) => item.ratio < 4.5)
      .slice(0, 8);
  });

  if (contrastFailures.length > 0) {
    throw new Error(`Expected '${expectedTitle}' dialog text contrast >= 4.5. Low contrast samples: ${JSON.stringify(contrastFailures)}.`);
  }
}

