async function createDefaultSr5PriorityRunner(page) {
  await openPreviewWithRetry(page);
  await page.waitForSelector('[data-testid="startup-workbench"]', { timeout: 15000 });
  await openNewCharacterDialog(page);

  let dialogTitle = (await page.locator('#dialogTitle').textContent()) || '';
  expectTextIncludes(dialogTitle, 'select build method', 'build-method dialog title');

  const dialog = page.locator('#dialogBackdrop');
  await fillDialogTextField(dialog, 'Character Name', 'Playwright Runner');
  await fillDialogTextField(dialog, 'Alias', 'PW');
  await fillDialogTextField(dialog, 'Ruleset', 'sr5');
  await fillDialogTextField(dialog, 'Build Method', 'Priority');
  await delay(300);

  const rulesetInput = dialog.locator('input[aria-label="Ruleset"]').first();
  const buildMethodInput = dialog.locator('input[aria-label="Build Method"]').first();
  if ((await rulesetInput.inputValue()).trim().toLowerCase() !== 'sr5') {
    throw new Error(`Expected selected ruleset 'sr5', got '${await rulesetInput.inputValue()}'.`);
  }

  if ((await buildMethodInput.inputValue()).trim().toLowerCase() !== 'priority') {
    throw new Error(`Expected selected build method 'priority', got '${await buildMethodInput.inputValue()}'.`);
  }

  await dialog.getByRole('button', { name: 'OK' }).click();
  await expectPremiumDialogPosture(page, 'select metatype priority');

  dialogTitle = (await page.locator('#dialogTitle').textContent()) || '';
  expectTextIncludes(dialogTitle, 'select metatype priority', 'metatype-priority dialog title');

  await page.locator('#dialogBackdrop').getByRole('button', { name: 'OK' }).click();
  await waitForWorkspaceLoaded(page, 'Playwright Runner', 'PW');

  const saveButton = page.getByRole('button', { name: 'Save' }).first();
  if (await saveButton.isDisabled()) {
    throw new Error('Save stayed disabled after opening the new workspace.');
  }
}

async function waitForWorkspaceLoaded(page, expectedName, expectedAlias) {
  await page.waitForFunction(({ expectedName, expectedAlias }) => {
    const summaryName = document.querySelector('#summaryName');
    const summaryAlias = document.querySelector('#summaryAlias');
    const charState = document.querySelector('#charState');
    return summaryName instanceof HTMLInputElement
      && summaryAlias instanceof HTMLInputElement
      && summaryName.value === expectedName
      && summaryAlias.value === expectedAlias
      && charState
      && charState.textContent
      && charState.textContent.toLowerCase().includes('loaded');
  }, { expectedName, expectedAlias }, { timeout: 20000 });
}

