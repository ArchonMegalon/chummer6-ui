function expectTextIncludes(actual, expected, context) {
  const haystack = (actual || '').toLowerCase();
  const needle = expected.toLowerCase();
  if (!haystack.includes(needle)) {
    throw new Error(`Expected ${context} to include '${expected}', got '${actual}'.`);
  }
}

function expectNoGeneratedAiCopy(actual, context) {
  const haystack = (actual || '').toLowerCase();
  const forbidden = [
    'generated by ai',
    'ai-generated',
    'ai generated',
    'as an ai',
    'as a large language model',
    'prompt seed:'
  ];

  for (const phrase of forbidden) {
    if (haystack.includes(phrase)) {
      throw new Error(`Expected ${context} to avoid '${phrase}' disclosure copy.`);
    }
  }
}

function expectMinimalHumanFacingCopy(actual, context) {
  expectNoGeneratedAiCopy(actual, context);

  const haystack = (actual || '').toLowerCase();
  const forbidden = [
    'generated asset',
    'generated assets',
    'flagship artifact',
    'artifact samples',
    'provider placeholders',
    'source packet',
    'prompt seed:',
    'operator-facing',
    'internal maintenance'
  ];

  for (const phrase of forbidden) {
    if (haystack.includes(phrase)) {
      throw new Error(`Expected ${context} to use customer-facing copy instead of '${phrase}'.`);
    }
  }
}

async function expectPremiumSurfaceQuality(page, context, rootSelector = 'body') {
  const root = page.locator(rootSelector).first();
  await root.waitFor({ state: 'attached', timeout: 15000 });

  const surfaceText = await root.innerText();
  expectMinimalHumanFacingCopy(surfaceText, context);

  const failures = await root.evaluate((surfaceRoot) => {
    function parseColor(value) {
      const match = /^rgba?\((\d+),\s*(\d+),\s*(\d+)(?:,\s*([0-9.]+))?\)$/.exec(value || '');
      if (!match) {
        return null;
      }

      return {
        r: Number(match[1]) / 255,
        g: Number(match[2]) / 255,
        b: Number(match[3]) / 255,
        a: match[4] === undefined ? 1 : Number(match[4])
      };
    }

    function linear(channel) {
      return channel <= 0.03928 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
    }

    function luminance(color) {
      return 0.2126 * linear(color.r) + 0.7152 * linear(color.g) + 0.0722 * linear(color.b);
    }

    function contrastRatio(foreground, background) {
      const l1 = luminance(foreground);
      const l2 = luminance(background);
      return (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
    }

    function blend(top, bottom) {
      const alpha = Math.max(0, Math.min(1, top.a));
      return {
        r: top.r * alpha + bottom.r * (1 - alpha),
        g: top.g * alpha + bottom.g * (1 - alpha),
        b: top.b * alpha + bottom.b * (1 - alpha),
        a: 1
      };
    }

    function effectiveBackground(element) {
      const layers = [];
      let current = element;
      while (current instanceof Element) {
        const color = parseColor(getComputedStyle(current).backgroundColor);
        if (color && color.a > 0.01) {
          layers.push(color);
        }

        current = current.parentElement;
      }

      return layers
        .reverse()
        .reduce((background, layer) => blend(layer, background), { r: 1, g: 1, b: 1, a: 1 });
    }

    function isVisible(node) {
      if (!(node instanceof Element)) {
        return false;
      }

      const style = getComputedStyle(node);
      const rect = node.getBoundingClientRect();
      return style.visibility !== 'hidden'
        && style.display !== 'none'
        && rect.width > 0
        && rect.height > 0
        && !node.closest('[hidden], [aria-hidden="true"]');
    }

    function visibleText(node) {
      if (node instanceof HTMLInputElement || node instanceof HTMLTextAreaElement) {
        if (node instanceof HTMLInputElement && ['range', 'color', 'file', 'checkbox', 'radio'].includes(node.type)) {
          return '';
        }

        return node.value || node.placeholder || node.getAttribute('aria-label') || '';
      }

      return node.textContent || node.getAttribute('aria-label') || '';
    }

    const contrastFailures = Array.from(surfaceRoot.querySelectorAll(
      'h1, h2, h3, h4, h5, p, span, strong, label, button, a, input, textarea, select, dt, dd, li, .note, .hint, .badge'))
      .filter((node) => {
        const text = visibleText(node);
        return isVisible(node) && text.trim().length > 0 && !node.hasAttribute('disabled');
      })
      .map((node) => {
        const style = getComputedStyle(node);
        const foreground = parseColor(style.color);
        const background = effectiveBackground(node);
        const ratio = foreground && background ? contrastRatio(foreground, background) : 99;
        return {
          text: visibleText(node).trim().replace(/\s+/g, ' ').slice(0, 90),
          ratio: Math.round(ratio * 100) / 100
        };
      })
      .filter((item) => item.ratio < 4.5)
      .slice(0, 8);

    const interactiveNodes = Array.from(surfaceRoot.querySelectorAll(
      'button, a[href], input, textarea, select, [role="button"], [role="tab"]'))
      .filter(isVisible);

    const unnamedTargets = interactiveNodes
      .filter((node) => {
        const name = (node.getAttribute('aria-label') || node.textContent || node.getAttribute('title') || '').trim();
        return name.length === 0;
      })
      .map((node) => node.outerHTML.slice(0, 140))
      .slice(0, 8);

    const smallTargets = interactiveNodes
      .map((node) => {
        const rect = node.getBoundingClientRect();
        return {
          text: visibleText(node).trim().replace(/\s+/g, ' ').slice(0, 80),
          width: Math.round(rect.width),
          height: Math.round(rect.height)
        };
      })
      .filter((item) => item.width < 24 || item.height < 24)
      .slice(0, 8);

    const clippedText = Array.from(surfaceRoot.querySelectorAll(
      'button, a, label, .mini-btn, .action-button, .tab-btn, .badge, h1, h2, h3, h4, h5'))
      .filter((node) => isVisible(node) && visibleText(node).trim().length > 0)
      .filter((node) => node.scrollWidth > node.clientWidth + 1 || node.scrollHeight > node.clientHeight + 1)
      .map((node) => ({
        text: visibleText(node).trim().replace(/\s+/g, ' ').slice(0, 90),
        clientWidth: node.clientWidth,
        scrollWidth: node.scrollWidth,
        clientHeight: node.clientHeight,
        scrollHeight: node.scrollHeight
      }))
      .slice(0, 8);

    const nativeFieldTooltips = Array.from(surfaceRoot.querySelectorAll('input[title], textarea[title], select[title]'))
      .filter(isVisible)
      .map((node) => ({
        text: visibleText(node).trim().replace(/\s+/g, ' ').slice(0, 80),
        title: (node.getAttribute('title') || '').trim().slice(0, 80)
      }))
      .filter((item) => item.title.length > 0)
      .slice(0, 8);

    const dialogLabelInputOverlaps = Array.from(surfaceRoot.querySelectorAll('.dialog-field'))
      .filter(isVisible)
      .map((field) => {
        const label = field.querySelector('.dialog-label');
        const control = field.querySelector('input, textarea, select');
        if (!label || !control || !isVisible(label) || !isVisible(control)) {
          return null;
        }

        const labelRect = label.getBoundingClientRect();
        const controlRect = control.getBoundingClientRect();
        const xOverlap = Math.max(0, Math.min(labelRect.right, controlRect.right) - Math.max(labelRect.left, controlRect.left));
        const yOverlap = Math.max(0, Math.min(labelRect.bottom, controlRect.bottom) - Math.max(labelRect.top, controlRect.top));
        const area = xOverlap * yOverlap;
        return area > 2
          ? {
            label: visibleText(label).trim().replace(/\s+/g, ' ').slice(0, 80),
            area: Math.round(area)
          }
          : null;
      })
      .filter(Boolean)
      .slice(0, 8);

    return {
      contrastFailures,
      unnamedTargets,
      smallTargets,
      clippedText,
      nativeFieldTooltips,
      dialogLabelInputOverlaps
    };
  });

  if (failures.contrastFailures.length > 0) {
    throw new Error(`Expected ${context} text contrast >= 4.5. Low contrast samples: ${JSON.stringify(failures.contrastFailures)}.`);
  }

  if (failures.unnamedTargets.length > 0) {
    throw new Error(`Expected ${context} interactive controls to have names. Samples: ${JSON.stringify(failures.unnamedTargets)}.`);
  }

  if (failures.smallTargets.length > 0) {
    throw new Error(`Expected ${context} mouse targets to be at least 24x24. Samples: ${JSON.stringify(failures.smallTargets)}.`);
  }

  if (failures.clippedText.length > 0) {
    throw new Error(`Expected ${context} labels to fit without clipping. Samples: ${JSON.stringify(failures.clippedText)}.`);
  }

  if (failures.nativeFieldTooltips.length > 0) {
    throw new Error(`Expected ${context} text fields to avoid native hover tooltips. Samples: ${JSON.stringify(failures.nativeFieldTooltips)}.`);
  }

  if (failures.dialogLabelInputOverlaps.length > 0) {
    throw new Error(`Expected ${context} dialog labels and controls not to overlap. Samples: ${JSON.stringify(failures.dialogLabelInputOverlaps)}.`);
  }
}

async function openRootWithRetry(page) {
  let lastError = null;
  for (let attempt = 1; attempt <= ROOT_NAV_RETRY_ATTEMPTS; attempt += 1) {
    try {
      await page.goto(`${UI_URL}/`, { waitUntil: NAVIGATION_WAIT_UNTIL, timeout: ROOT_NAV_TIMEOUT_MS });
      return;
    } catch (error) {
      lastError = error;
      if (attempt >= ROOT_NAV_RETRY_ATTEMPTS) {
        break;
      }

      // Service startup can lag briefly in containerized runs; retry before failing the suite.
      await delay(ROOT_NAV_RETRY_DELAY_MS);
    }
  }

  throw lastError || new Error(`Unable to open ${UI_URL}/`);
}

