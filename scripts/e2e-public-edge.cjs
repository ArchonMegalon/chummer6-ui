#!/usr/bin/env node
'use strict';

const baseUrl = (process.env.CHUMMER_PORTAL_BASE_URL || 'http://127.0.0.1:8091').replace(/\/$/, '');
const portalPublicHost = process.env.CHUMMER_PORTAL_PUBLIC_HOST || 'chummer.run';
const useForwardedPublicHeaders = /^http:\/\/(?:127\.0\.0\.1|localhost)(?::\d+)?$/i.test(baseUrl);
const defaultHeaders = useForwardedPublicHeaders
  ? {
      Host: portalPublicHost,
      'X-Forwarded-Proto': 'https'
    }
  : {};

const requiredLandingLinks = [
  '/downloads',
  '/help',
  '/contact'
];

function mergeHeaders(headers) {
  return { ...defaultHeaders, ...(headers || {}) };
}

function hasBlazorBaseHref(html) {
  return /<base href="[^"]*\/blazor\/"/i.test(html);
}

function hasPortalChrome(text) {
  return text.includes('--portal-gold: #ffd46f')
    && text.includes('--portal-mint: #8ff0bc')
    && text.includes('body::before')
    && text.includes('background-size: 4.25rem 4.25rem')
    && text.includes('@keyframes portal-surface-reveal')
    && text.includes('animation: portal-surface-reveal .38s cubic-bezier(.2,.78,.2,1) both');
}

function assertNamedRequirements(context, requirements) {
  const failed = Object.entries(requirements)
    .filter(([, passed]) => !passed)
    .map(([name]) => name);

  if (failed.length > 0) {
    throw new Error(`${context} missing requirements: ${failed.join(', ')}`);
  }

  return true;
}

function visibleText(html) {
  return html
    .replace(/<script\b[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style\b[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function avoidsFrontDoorNoise(html) {
  const text = visibleText(html).toLowerCase();
  return !text.includes('generated by ai')
    && !text.includes('ai-generated')
    && !text.includes('proof receipt')
    && !text.includes('account-assisted install');
}

function avoidsParticipateFailureCopy(html) {
  const text = visibleText(html).toLowerCase();
  return !text.includes('something went wrong on our side')
    && !text.includes('could not load posts')
    && !text.includes('network error while loading tab configuration')
    && !text.includes('support@productlift.dev');
}

function isAcceptedRedirectStatus(status) {
  return [301, 302, 303, 307, 308].includes(status);
}

function publicInstallerRedirectMatches(response, artifactId) {
  const location = response.headers.get('location') || '';
  const expectedLocation = `/downloads/get/${artifactId}`;
  return isAcceptedRedirectStatus(response.status)
    && (location === expectedLocation || decodeURIComponent(location) === expectedLocation)
    && !decodeURIComponent(location).includes('/login?next=');
}

const checks = [
  {
    url: `${baseUrl}/`,
    assert: text => assertNamedRequirements('public portal landing page', {
      headline: text.includes('Explore Chummer Online, downloads, and support from one self-hosted edge.'),
      'roster guidance': text.includes('Start in the Character Roster, continue into Chummer Online'),
      'primary app action': text.includes('data-portal-home-action="explore-chummer-online"'),
      'roster command route': text.includes('/app?command=character_roster'),
      'route navigation label': text.includes('aria-label="Chummer Online routes"'),
      'roster route marker': text.includes('data-portal-home-route="chummer-app-roster"'),
      'app route marker': text.includes('data-portal-home-route="chummer-app"'),
      'home route marker': text.includes('data-portal-home-route="chummer-home"'),
      'downloads route marker': text.includes('data-portal-home-route="downloads"'),
      'contact route marker': text.includes('data-portal-home-route="contact"'),
      'required recovery links': requiredLandingLinks.every(link => text.includes(link)),
      'portal chrome': hasPortalChrome(text),
      'human-facing copy': avoidsFrontDoorNoise(text)
    })
  },
  {
    url: `${baseUrl}/downloads`,
    assert: text => assertNamedRequirements('public downloads surface', {
      panel: text.includes('data-download-panel="desktop-downloads"'),
      'manifest link': text.includes('data-download-manifest-link'),
      'artifact action': text.includes('data-download-action="download-artifact"'),
      'windows installer': text.includes('data-download-artifact="avalonia-win-x64-installer"'),
      'windows install route': text.includes('data-download-install-route="/downloads/install/avalonia-win-x64-installer"'),
      'linux installer': text.includes('data-download-artifact="avalonia-linux-x64-installer"'),
      'linux install route': text.includes('data-download-install-route="/downloads/install/avalonia-linux-x64-installer"'),
      'self-host dispatch': text.includes('data-download-link-mode="self-host-dispatch"'),
      'proof-required boundary': text.includes('data-self-host-installer-boundary="proof-required"'),
      'portal chrome': hasPortalChrome(text),
      'human-facing copy': avoidsFrontDoorNoise(text)
    })
  },
  {
    url: `${baseUrl}/downloads/releases.json`,
    assert: text => {
      const payload = JSON.parse(text);
      const displayVersion = typeof payload?.displayVersion === 'string'
        ? payload.displayVersion.trim()
        : String(payload?.version || '').trim();
      const linuxRow = Array.isArray(payload?.downloads)
        ? payload.downloads.find(row => row?.artifactId === 'avalonia-linux-x64-installer')
        : null;
      const windowsRow = Array.isArray(payload?.downloads)
        ? payload.downloads.find(row => row?.artifactId === 'avalonia-win-x64-installer')
        : null;
      return typeof payload?.version === 'string'
        && typeof payload?.channel === 'string'
        && displayVersion.length > 0
        && payload?.status === 'published'
        && Array.isArray(payload?.downloads)
        && payload.downloads.length > 0
        && linuxRow?.head === 'avalonia'
        && linuxRow?.platform === 'linux'
        && linuxRow?.platformId === 'linux-x64'
        && linuxRow?.installAccessClass === 'open_public'
        && windowsRow?.head === 'avalonia'
        && windowsRow?.platform === 'windows'
        && windowsRow?.platformId === 'windows-x64'
        && windowsRow?.installAccessClass === 'open_public';
    }
  },
  {
    url: `${baseUrl}/downloads/install/avalonia-linux-x64-installer`,
    redirect: 'manual',
    acceptedStatuses: [301, 302, 303, 307, 308],
    assert: (_text, response) => publicInstallerRedirectMatches(response, 'avalonia-linux-x64-installer')
  },
  {
    url: `${baseUrl}/downloads/install/avalonia-win-x64-installer`,
    redirect: 'manual',
    acceptedStatuses: [301, 302, 303, 307, 308],
    assert: (_text, response) => publicInstallerRedirectMatches(response, 'avalonia-win-x64-installer')
  },
  {
    url: `${baseUrl}/status`,
    assert: text => assertNamedRequirements('public status surface', {
      panel: text.includes('data-portal-status-panel="release-availability"'),
      availability: text.includes('data-portal-status-availability='),
      release: text.includes('data-portal-status-release-status='),
      downloads: text.includes('data-portal-status-action="open-downloads"'),
      help: text.includes('data-portal-status-action="open-help"'),
      support: text.includes('data-portal-status-action="open-discord"'),
      app: text.includes('data-portal-status-action="open-chummer-app"'),
      'portal chrome': hasPortalChrome(text),
      'human-facing copy': avoidsFrontDoorNoise(text)
    })
  },
  {
    url: `${baseUrl}/help`,
    assert: text => assertNamedRequirements('public help surface', {
      panel: text.includes('data-portal-help-panel="handoff-guide"'),
      context: text.includes('data-portal-help-context='),
      downloads: text.includes('data-portal-help-action="open-downloads"'),
      status: text.includes('data-portal-help-action="open-status"'),
      support: text.includes('data-portal-help-action="open-discord"'),
      contact: text.includes('data-portal-help-action="open-contact"'),
      docs: text.includes('data-portal-help-action="open-docs"'),
      'source boundary': text.includes('data-portal-help-boundary="source-guidance-only"'),
      'portal chrome': hasPortalChrome(text),
      'human-facing copy': avoidsFrontDoorNoise(text)
    })
  },
  {
    url: `${baseUrl}/contact`,
    assert: text => assertNamedRequirements('public contact surface', {
      panel: text.includes('data-portal-contact-panel="support-handoff"'),
      context: text.includes('data-portal-contact-context='),
      route: text.includes('data-portal-contact-public-route='),
      support: text.includes('data-portal-contact-action="open-discord"'),
      status: text.includes('data-portal-contact-action="open-status"'),
      downloads: text.includes('data-portal-contact-action="open-downloads"'),
      help: text.includes('data-portal-contact-action="open-help"'),
      app: text.includes('data-portal-contact-action="open-chummer-app"'),
      'portal chrome': hasPortalChrome(text),
      'human-facing copy': avoidsFrontDoorNoise(text)
    })
  },
  {
    url: `${baseUrl}/what-is-chummer`,
    assert: text =>
      text.includes('Character tools for Shadowrun.')
      && text.includes('Downloads first')
      && text.includes('Downloads')
      && text.includes('Help')
      && text.includes('Status')
      && avoidsFrontDoorNoise(text)
  },
  {
    url: `${baseUrl}/play`,
    assert: text =>
      text.includes('Player entry')
      && text.includes('Install like an app. Re-enter like a session shell.')
      && text.includes('One mobile view, five clear promises.')
      && text.includes('Player, GM, and observer entry points meet in one shell.')
      && text.includes('Open mobile and PWA')
      && text.includes('Open continuity')
      && text.includes('Open downloads')
  },
  {
    url: `${baseUrl}/ledger`,
    assert: (text, response) =>
      response.url.includes('/ledger/map')
      && text.includes('Black Ledger command map')
      && text.includes('Fictional campaign pressure, package heat, and closeout movement.')
  },
  {
    url: `${baseUrl}/ledger/factions`,
    assert: text =>
      text.includes('Black Ledger faction files')
      && text.includes('Use faction posture, pressure, and consequences to brief the next session cleanly.')
      && text.includes('Open command map')
      && text.includes('Open newsroom')
      && text.includes('Open player entry')
  },
  {
    url: `${baseUrl}/ledger/newsroom`,
    assert: text =>
      text.includes('Black Ledger newsroom')
      && text.includes('Follow turn-ready updates, pressure notes, and closeout context from the same Black Ledger lane.')
      && text.includes('Open command map')
      && text.includes('Open factions')
      && text.includes('Open player entry')
  },
  {
    url: `${baseUrl}/artifacts`,
    assert: text =>
      text.includes('Detail gallery')
      && text.includes('Detail surfaces, briefs, and clear outputs connected to the current public release.')
  },
  {
    url: `${baseUrl}/roadmap`,
    assert: (text, response) =>
      response.url.includes('/participate')
      && text.includes('Participate - Chummer.run')
      && text.includes('Public bugs and requests')
      && avoidsParticipateFailureCopy(text)
  },
  {
    url: `${baseUrl}/participate`,
    assert: text =>
      text.includes('Participate - Chummer.run')
      && text.includes('Public bugs and requests')
      && text.includes('data-portal-participate-frame')
      && avoidsParticipateFailureCopy(text)
  },
  {
    url: `${baseUrl}/hub`,
    assert: text =>
      /<base href="[^"]*\/hub\/"/i.test(text)
      && (text.includes('ChummerHub Web') || text.includes('Chummer Hub Web'))
  },
  {
    url: `${baseUrl}/blazor/`,
    assert: (text, response) => assertNamedRequirements('public Blazor root app redirect', {
      'app redirect target': response.url.includes('/blazor/app')
        && response.url.includes('command=character_roster'),
      'configured base path': hasBlazorBaseHref(text),
      'app route marker': text.includes('data-route-family="app"'),
      'character roster': text.includes('Character Roster')
    })
  },
  {
    url: `${baseUrl}/app`,
    assert: text =>
      hasBlazorBaseHref(text)
      && text.includes('data-route-family="app"')
  },
  {
    url: `${baseUrl}/app?command=character_roster`,
    assert: text =>
      hasBlazorBaseHref(text)
      && text.includes('Character Roster')
      && text.includes('data-command="character-roster"')
  },
  {
    url: `${baseUrl}/blazor/home`,
    assert: text => assertNamedRequirements('public Blazor interactive home bootstrap', {
      'configured base path': hasBlazorBaseHref(text),
      'Blazor runtime script': text.includes('_framework/blazor.web.js'),
      'PWA install shell': text.includes('data-build-pwa-install-help')
    })
  },
  {
    url: `${baseUrl}/blazor/app`,
    assert: text =>
      hasBlazorBaseHref(text)
      && text.includes('data-route-family="app"')
  },
  {
    url: `${baseUrl}/session/`,
    assert: (text, response) =>
      response.url.endsWith('/play')
      && text.includes('Player entry')
  },
  {
    url: `${baseUrl}/coach/`,
    assert: (text, response) =>
      response.url.endsWith('/status')
      && text.includes('Windows and Linux downloads are live.')
  },
  {
    url: `${baseUrl}/openapi/v1.json`,
    assert: text => {
      const payload = JSON.parse(text);
      return typeof payload?.openapi === 'string'
        && typeof payload?.paths?.['/help'] === 'object'
        && typeof payload?.paths?.['/app'] === 'object'
        && typeof payload?.paths?.['/contact'] === 'object'
        && typeof payload?.paths?.['/status'] === 'object'
        && typeof payload?.paths?.['/blazor/app'] === 'object'
        && typeof payload?.paths?.['/blazor/home'] === 'object'
        && typeof payload?.paths?.['/blazor/'] === 'object'
        && typeof payload?.paths?.['/downloads/'] === 'object'
        && typeof payload?.paths?.['/downloads/releases.json'] === 'object'
        && typeof payload?.paths?.['/downloads/install/{artifactId}'] === 'object'
        && typeof payload?.paths?.['/play'] === 'object'
        && typeof payload?.paths?.['/ledger'] === 'object'
        && typeof payload?.paths?.['/ledger/map'] === 'object'
        && typeof payload?.paths?.['/ledger/factions'] === 'object'
        && typeof payload?.paths?.['/ledger/newsroom'] === 'object'
        && typeof payload?.paths?.['/participate'] === 'object'
        && typeof payload?.paths?.['/roadmap'] === 'object'
        && typeof payload?.paths?.['/session/'] === 'object'
        && typeof payload?.paths?.['/coach/'] === 'object'
        && payload?.paths?.['/ledger/factions']?.get?.summary === 'Open the Black Ledger faction files surface'
        && payload?.paths?.['/ledger/newsroom']?.get?.summary === 'Open the Black Ledger newsroom surface';
    }
  }
];

(async () => {
  for (const check of checks) {
    const response = await fetch(check.url, {
      method: check.method ?? 'GET',
      headers: mergeHeaders(check.headers),
      body: check.body,
      redirect: check.redirect
    });
    const body = await response.text();
    const acceptedStatuses = check.acceptedStatuses || [];
    const statusAccepted = response.ok || acceptedStatuses.includes(response.status);
    if (!statusAccepted) {
      throw new Error(`Portal check failed: ${check.url} -> HTTP ${response.status}`);
    }

    let passed = false;
    try {
      passed = Boolean(check.assert(body, response));
    } catch (error) {
      throw new Error(`Portal check failed: ${check.url} -> assertion threw: ${error.message}`);
    }

    if (!passed) {
      throw new Error(`Portal check failed: ${check.url} -> assertion returned false`);
    }

    console.log(`ok: ${check.url}`);
  }

  console.log('public edge E2E completed');
})().catch(error => {
  console.error(error.message);
  process.exit(1);
});
