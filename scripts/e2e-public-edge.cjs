#!/usr/bin/env node
'use strict';

const baseUrl = (process.env.CHUMMER_PORTAL_BASE_URL || 'http://127.0.0.1:8091').replace(/\/$/, '');
const portalPublicHost = process.env.CHUMMER_PORTAL_PUBLIC_HOST || 'chummer.run';
const useForwardedPublicHeaders = /^http:\/\/(?:127\.0\.0\.1|localhost)(?::\d+)?$/i.test(baseUrl);
const defaultHeaders = useForwardedPublicHeaders
  ? {
      Host: portalPublicHost,
      'X-Forwarded-Proto': 'https'
    }
  : {};

const requiredLandingLinks = [
  '/downloads',
  '/help',
  '/status',
  '/contact'
];

function mergeHeaders(headers) {
  return { ...defaultHeaders, ...(headers || {}) };
}

function hasBlazorBaseHref(html) {
  return /<base href="[^"]*\/blazor\/"/i.test(html);
}

function visibleText(html) {
  return html
    .replace(/<script\b[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style\b[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function avoidsFrontDoorNoise(html) {
  const text = visibleText(html).toLowerCase();
  return !text.includes('generated by ai')
    && !text.includes('ai-generated')
    && !text.includes('proof receipt')
    && !text.includes('account-assisted install')
    && !text.includes('workspace');
}

function avoidsParticipateFailureCopy(html) {
  const text = visibleText(html).toLowerCase();
  return !text.includes('something went wrong on our side')
    && !text.includes('could not load posts')
    && !text.includes('network error while loading tab configuration')
    && !text.includes('support@productlift.dev');
}

function isAcceptedRedirectStatus(status) {
  return [301, 302, 303, 307, 308].includes(status);
}

function publicInstallerRedirectMatches(response, artifactId) {
  const location = response.headers.get('location') || '';
  const expectedLocation = `/downloads/get/${artifactId}`;
  return isAcceptedRedirectStatus(response.status)
    && (location === expectedLocation || decodeURIComponent(location) === expectedLocation)
    && !decodeURIComponent(location).includes('/login?next=');
}

const checks = [
  {
    url: `${baseUrl}/`,
    assert: text =>
      text.includes('Download Chummer')
      && text.includes('A Shadowrun character manager for clean sheets and faster tables.')
      && text.includes('Current public installers: Windows and Linux.')
      && text.includes('Watch the Chummer promo video')
      && text.includes('Watch 90 sec')
      && requiredLandingLinks.every(link => text.includes(link))
      && avoidsFrontDoorNoise(text)
  },
  {
    url: `${baseUrl}/downloads`,
    assert: text =>
      text.includes('<h1>Downloads</h1>')
      && text.includes('Recommended from your browser. Other platforms stay out of the way.')
      && text.includes('Stable')
      && text.includes('Recommended for this browser.')
      && text.includes('data-download-action="download-artifact"')
      && text.includes('data-download-artifact="avalonia-win-x64-installer"')
      && text.includes('data-download-install-route="/downloads/install/avalonia-win-x64-installer"')
      && text.includes('data-download-action="download-artifact"')
      && text.includes('Nightly')
      && text.includes('No newer Nightly right now.')
      && text.includes('Other downloads')
      && text.includes('Build from source')
      && text.includes('No sudo. Updates default to notify.')
      && text.includes('/downloads/build-chummer6-linux.sh')
      && text.includes('data-download-artifact="avalonia-linux-x64-installer"')
      && text.includes('data-download-install-route="/downloads/install/avalonia-linux-x64-installer"')
      && avoidsFrontDoorNoise(text)
  },
  {
    url: `${baseUrl}/downloads/releases.json`,
    assert: text => {
      const payload = JSON.parse(text);
      const linuxRow = Array.isArray(payload?.downloads)
        ? payload.downloads.find(row => row?.artifactId === 'avalonia-linux-x64-installer')
        : null;
      const windowsRow = Array.isArray(payload?.downloads)
        ? payload.downloads.find(row => row?.artifactId === 'avalonia-win-x64-installer')
        : null;
      return typeof payload?.version === 'string'
        && typeof payload?.channel === 'string'
        && typeof payload?.displayVersion === 'string'
        && payload?.status === 'published'
        && Array.isArray(payload?.downloads)
        && payload.downloads.length > 0
        && linuxRow?.head === 'avalonia'
        && linuxRow?.platformId === 'linux'
        && linuxRow?.installAccessClass === 'open_public'
        && windowsRow?.head === 'avalonia'
        && windowsRow?.platformId === 'windows'
        && windowsRow?.installAccessClass === 'open_public';
    }
  },
  {
    url: `${baseUrl}/downloads/install/avalonia-linux-x64-installer`,
    redirect: 'manual',
    acceptedStatuses: [301, 302, 303, 307, 308],
    assert: (_text, response) => publicInstallerRedirectMatches(response, 'avalonia-linux-x64-installer')
  },
  {
    url: `${baseUrl}/downloads/install/avalonia-win-x64-installer`,
    redirect: 'manual',
    acceptedStatuses: [301, 302, 303, 307, 308],
    assert: (_text, response) => publicInstallerRedirectMatches(response, 'avalonia-win-x64-installer')
  },
  {
    url: `${baseUrl}/downloads/build-chummer6-linux.sh`,
    assert: text =>
      text.startsWith('#!/usr/bin/env bash')
      && text.includes('Build the Chummer6 Avalonia desktop client from source for this Linux computer.')
      && text.includes('CHUMMER_GITHUB_ORG')
      && text.includes('CHUMMER_GIT_REF')
      && text.includes('CHUMMER_BUILD_BASE')
  },
  {
    url: `${baseUrl}/status`,
    assert: text =>
      text.includes('<h1>Updated</h1>')
      && text.includes('Windows and Linux downloads are live.')
      && text.includes('href="/downloads"')
      && text.includes('href="/help"')
      && text.includes('Status')
      && avoidsFrontDoorNoise(text)
  },
  {
    url: `${baseUrl}/help`,
    assert: text =>
      text.includes('<h1 class="">Help</h1>')
      && text.includes('Start here')
      && text.includes('Open downloads')
      && text.includes('/contact#support-intake')
      && text.includes('Support, installs, and recovery.')
      && avoidsFrontDoorNoise(text)
  },
  {
    url: `${baseUrl}/contact`,
    assert: text =>
      text.includes('<h1 class="">Contact</h1>')
      && text.includes('Discord for normal questions.')
      && text.includes('Open Discord')
      && text.includes('Open private form')
      && text.includes('Private help')
      && text.includes('<form class="settings-form" method="post" action="/contact"')
      && text.includes('Reply email')
      && text.includes('Keep normal questions in Discord.')
      && avoidsFrontDoorNoise(text)
  },
  {
    url: `${baseUrl}/now`,
    assert: text =>
      text.includes('What works today')
      && text.includes('Start from downloads.')
      && text.includes('Use help before you guess.')
      && text.includes('Keep installs and support history together')
      && text.includes('Open downloads')
      && text.includes('Open help')
      && avoidsFrontDoorNoise(text)
  },
  {
    url: `${baseUrl}/faq`,
    assert: text =>
      text.includes('Plain answers before you spend more time')
      && text.includes('Quick paths')
      && text.includes('Use support for private problems')
      && text.includes('Open status')
      && text.includes('Open downloads')
      && text.includes('Open support')
      && avoidsFrontDoorNoise(text)
  },
  {
    url: `${baseUrl}/what-is-chummer`,
    assert: text =>
      text.includes('Character tools for Shadowrun.')
      && text.includes('Downloads first')
      && text.includes('Downloads')
      && text.includes('Help')
      && text.includes('Status')
      && avoidsFrontDoorNoise(text)
  },
  {
    url: `${baseUrl}/play`,
    assert: text =>
      text.includes('Player entry')
      && text.includes('Install like an app. Re-enter like a session shell.')
      && text.includes('One mobile view, five clear promises.')
      && text.includes('Player, GM, and observer entry points meet in one shell.')
      && text.includes('Open mobile and PWA')
      && text.includes('Open continuity')
      && text.includes('Open downloads')
  },
  {
    url: `${baseUrl}/ledger`,
    assert: (text, response) =>
      response.url.includes('/ledger/map')
      && text.includes('Black Ledger command map')
      && text.includes('Fictional campaign pressure, package heat, and closeout movement.')
  },
  {
    url: `${baseUrl}/artifacts`,
    assert: text =>
      text.includes('Detail gallery')
      && text.includes('Detail surfaces, briefs, and clear outputs connected to the current public release.')
  },
  {
    url: `${baseUrl}/roadmap`,
    assert: (text, response) =>
      response.url.includes('/participate')
      && text.includes('Participate - Chummer.run')
      && text.includes('Public bugs and requests')
      && avoidsParticipateFailureCopy(text)
  },
  {
    url: `${baseUrl}/participate`,
    assert: text =>
      text.includes('Participate - Chummer.run')
      && text.includes('Public bugs and requests')
      && avoidsParticipateFailureCopy(text)
  },
  {
    url: `${baseUrl}/hub`,
    assert: (text, response) =>
      response.url.includes('/login?next=%2Faccount')
      && text.includes('Open Chummer')
      && text.includes('Use email first. Google is optional.')
  },
  {
    url: `${baseUrl}/blazor/`,
    assert: text =>
      text.includes('Browser preview is not ready right now.')
      && text.includes('The downloadable Chummer client is the current stable path.')
      && text.includes('Download Chummer')
  },
  {
    url: `${baseUrl}/app`,
    assert: text =>
      hasBlazorBaseHref(text)
      && text.includes('Explore Chummer Online.')
      && text.includes('This is the Chummer Online entrypoint')
      && text.includes('data-chummer-classic-shell="true"')
  },
  {
    url: `${baseUrl}/app?command=character_roster`,
    assert: text =>
      hasBlazorBaseHref(text)
      && text.includes('Explore Chummer Online.')
      && text.includes('Character Roster')
      && text.includes('data-command="character-roster"')
  },
  {
    url: `${baseUrl}/blazor/home`,
    assert: text =>
      hasBlazorBaseHref(text)
      && text.includes('Chummer Online for real runner work.')
      && text.includes('Explore Chummer Online')
      && text.includes('data-home-hero-action="explore-chummer-online"')
      && text.includes('Roster entry:')
  },
  {
    url: `${baseUrl}/blazor/app`,
    assert: text =>
      hasBlazorBaseHref(text)
      && text.includes('Explore Chummer Online.')
      && text.includes('data-chummer-classic-shell="true"')
  },
  {
    url: `${baseUrl}/session/`,
    assert: (text, response) =>
      response.url.endsWith('/play')
      && text.includes('Player entry')
  },
  {
    url: `${baseUrl}/coach/`,
    assert: (text, response) =>
      response.url.endsWith('/status')
      && text.includes('Windows and Linux downloads are live.')
  }
];

(async () => {
  for (const check of checks) {
    const response = await fetch(check.url, {
      method: check.method ?? 'GET',
      headers: mergeHeaders(check.headers),
      body: check.body,
      redirect: check.redirect
    });
    const body = await response.text();
    const acceptedStatuses = check.acceptedStatuses || [];
    const statusAccepted = response.ok || acceptedStatuses.includes(response.status);
    if (!statusAccepted) {
      throw new Error(`Portal check failed: ${check.url} -> HTTP ${response.status}`);
    }

    let passed = false;
    try {
      passed = Boolean(check.assert(body, response));
    } catch (error) {
      throw new Error(`Portal check failed: ${check.url} -> assertion threw: ${error.message}`);
    }

    if (!passed) {
      throw new Error(`Portal check failed: ${check.url} -> assertion returned false`);
    }

    console.log(`ok: ${check.url}`);
  }

  console.log('public edge E2E completed');
})().catch(error => {
  console.error(error.message);
  process.exit(1);
});
